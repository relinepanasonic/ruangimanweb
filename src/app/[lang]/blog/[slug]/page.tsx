import type { Metadata } from "next";
import Link from "next/link";
import Image from "next/image";
import { notFound } from "next/navigation";
import ReactMarkdown from "react-markdown";
import remarkGfm from "remark-gfm";
import Reveal from "@/components/Reveal";
import PostCard from "@/components/PostCard";
import CTASection from "@/components/home/CTASection";
import { getDictionary } from "@/i18n/get-dictionary";
import { locales, localeHtmlLang, type Locale } from "@/i18n/config";
import {
  getPostBySlug,
  getPublishedPosts,
  formatDate,
  prettifyCategory,
  readingMinutes,
} from "@/lib/blog";
import { href, SITE_URL, SITE_NAME } from "@/lib/site";

export const revalidate = 3600;
// A post published after the last build should still render on first request
// rather than 404 — ISR fills it in from there.
export const dynamicParams = true;

export async function generateStaticParams() {
  const posts = await getPublishedPosts();
  return locales.flatMap((lang) =>
    posts.map((post) => ({ lang, slug: post.slug })),
  );
}

export async function generateMetadata({
  params,
}: {
  params: Promise<{ lang: string; slug: string }>;
}): Promise<Metadata> {
  const { lang, slug } = await params;
  const post = await getPostBySlug(slug);
  if (!post) return { title: getDictionary(lang).blog.notFound };

  const path = `/${lang}/blog/${slug}`;
  return {
    title: post.title,
    description: post.meta_description,
    keywords: post.tags,
    authors: [{ name: post.author_name }],
    alternates: {
      canonical: path,
      languages: {
        id: `/id/blog/${slug}`,
        en: `/en/blog/${slug}`,
        "x-default": `/id/blog/${slug}`,
      },
    },
    openGraph: {
      type: "article",
      title: post.title,
      description: post.meta_description,
      url: `${SITE_URL}${path}`,
      publishedTime: post.published_at ?? undefined,
      modifiedTime: post.updated_at ?? undefined,
      authors: [post.author_name],
      tags: post.tags,
      // og:image is generated by the sibling opengraph-image.tsx.
    },
    twitter: {
      card: "summary_large_image",
      title: post.title,
      description: post.meta_description,
    },
  };
}

export default async function BlogPostPage({
  params,
}: {
  params: Promise<{ lang: string; slug: string }>;
}) {
  const { lang, slug } = await params;
  const locale = lang as Locale;
  const dict = getDictionary(lang);

  const post = await getPostBySlug(slug);
  if (!post) notFound();

  const related = (await getPublishedPosts(4))
    .filter((item) => item.slug !== slug)
    .slice(0, 3);

  return (
    <>
      <article className="bg-brand-bg">
        <header className="grain relative overflow-hidden px-5 pb-14 pt-32 sm:px-8 sm:pt-40">
          <div
            aria-hidden="true"
            className="pointer-events-none absolute inset-0 -z-10"
            style={{
              background:
                "radial-gradient(58% 70% at 30% 0%, rgba(57,79,107,0.5), transparent 70%), linear-gradient(180deg, #1b1e23 0%, #272a30 100%)",
            }}
          />
          <div className="mx-auto max-w-3xl">
            <Link
              href={href(locale, "blog")}
              className="group inline-flex items-center gap-2 text-sm text-brand-muted transition-colors hover:text-brand-gold"
            >
              <span
                aria-hidden="true"
                className="transition-transform duration-300 group-hover:-translate-x-1"
              >
                ←
              </span>
              {dict.blog.backToBlog}
            </Link>

            <div className="mt-8 flex flex-wrap items-center gap-3 text-[0.7rem] uppercase tracking-[0.14em]">
              <span className="rounded-full border border-brand-gold/25 bg-brand-gold/8 px-2.5 py-1 font-semibold text-brand-gold">
                {prettifyCategory(post.category)}
              </span>
              <span className="text-brand-muted">
                {formatDate(post.published_at, locale)}
              </span>
              <span className="text-brand-muted">
                · {readingMinutes(post.content)} {dict.blog.minRead}
              </span>
            </div>

            <h1 className="mt-6 text-balance text-[clamp(2rem,5.4vw,3.75rem)] font-bold leading-[1.05] tracking-[-0.04em] text-brand-light">
              {post.title}
            </h1>

            <p className="mt-6 text-lg leading-relaxed text-brand-muted">
              {post.excerpt}
            </p>

            <p className="mt-7 text-sm text-brand-muted">
              {dict.blog.by}{" "}
              <span className="text-brand-light">{post.author_name}</span>
            </p>
          </div>
        </header>

        {post.cover_image_url && (
          <div className="mx-auto max-w-4xl px-5 sm:px-8">
            <div className="relative aspect-[16/9] overflow-hidden rounded-2xl ring-1 ring-white/10">
              <Image
                src={post.cover_image_url}
                alt=""
                fill
                priority
                sizes="(max-width: 896px) 100vw, 896px"
                className="object-cover"
              />
            </div>
          </div>
        )}

        <div className="mx-auto max-w-3xl px-5 py-16 sm:px-8 sm:py-20">
          <div className="prose-iman">
            <ReactMarkdown remarkPlugins={[remarkGfm]}>
              {post.content}
            </ReactMarkdown>
          </div>

          {post.tags.length > 0 && (
            <ul className="mt-14 flex flex-wrap gap-2 border-t border-white/8 pt-8">
              {post.tags.map((tag) => (
                <li
                  key={tag}
                  className="rounded-full border border-white/12 px-3 py-1.5 text-xs text-brand-muted"
                >
                  #{tag}
                </li>
              ))}
            </ul>
          )}
        </div>
      </article>

      {related.length > 0 && (
        <section className="bg-brand-dark px-5 py-24 sm:px-8">
          <div className="mx-auto max-w-6xl">
            <h2 className="text-xl font-semibold tracking-tight text-brand-light">
              {dict.blog.relatedHeading}
            </h2>
            <ul className="mt-8 grid gap-6 sm:grid-cols-2 lg:grid-cols-3">
              {related.map((item, index) => (
                <Reveal key={item.slug} as="li" delay={0.06 * index}>
                  <PostCard post={item} lang={locale} />
                </Reveal>
              ))}
            </ul>
          </div>
        </section>
      )}

      <CTASection dict={dict} />

      <script
        type="application/ld+json"
        dangerouslySetInnerHTML={{
          __html: JSON.stringify({
            "@context": "https://schema.org",
            "@type": "Article",
            headline: post.title,
            description: post.meta_description,
            image: [
              post.cover_image_url ??
                // The generated share card, same route + Next's convention path.
                `${SITE_URL}/${locale}/blog/${slug}/opengraph-image`,
            ],
            datePublished: post.published_at,
            dateModified: post.updated_at ?? post.published_at,
            inLanguage: localeHtmlLang[locale],
            keywords: post.tags.join(", "),
            author: { "@type": "Organization", name: post.author_name },
            publisher: {
              "@type": "Organization",
              name: SITE_NAME,
              logo: {
                "@type": "ImageObject",
                // Square, per Google's Article publisher-logo guidance —
                // the full RUANGIMAN lockup with its wordmark is not.
                url: `${SITE_URL}/logo-mark.png`,
              },
            },
            mainEntityOfPage: {
              "@type": "WebPage",
              "@id": `${SITE_URL}/${locale}/blog/${slug}`,
            },
          }),
        }}
      />
    </>
  );
}
